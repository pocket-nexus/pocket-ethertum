#!/usr/bin/env bun
/**
 * Compiles the interface (`ui/`, one PocketJS app) for a device. PocketJS
 * resolves `ui/pocket.json` against the device's profile and writes the
 * bundle and its pak.
 *
 *   bun tools/ui.ts vita        → .pocket-build/ui/vita/ether.{js,pak}, plan.json
 *   bun tools/ui.ts prepare     → the pictures the interface compiles from the reference's art (ui/app/generated/)
 *   bun tools/ui.ts preview     → pictures of every screen, .pocket-build/ui/preview/
 *   bun tools/ui.ts test        → the interface driven through a mock renderer
 */
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { extractHostBuildInputs, type HostBuildInputs } from "../vendor/pocketjs/framework/src/manifest/index.ts";
import { createCanvas, loadImage, type Image } from "../vendor/pocketjs/node_modules/@napi-rs/canvas";

export const DEVICES = ["vita"] as const;
export type Device = (typeof DEVICES)[number];

const root = resolve(import.meta.dir, "..");
const pocket = join(root, "vendor/pocketjs");
const project = join(root, "ui");
const manifest = join(project, "pocket.json");
const generated = join(project, "app/generated");
const baked = join(root, "ref/ethertum/assets/baked");

/** Tiles in the reference's diffuse atlas (`atlas_diff.png`, 24 × 256²), and icons in `items.png` (10 × 64²). */
const TILES = 24;
const ICONS = 10;
/** Logical side of a hotbar picture: a pak image is a power of two. The `@2x` file is for the Vita's raster. */
const SIDE = 32;

export interface Interface {
  /** Directory holding `ether.js`, `ether.pak` and `plan.json`. */
  directory: string;
  inputs: HostBuildInputs;
  plan: { features: Record<string, boolean> };
}

function run(args: string[], cwd = pocket) {
  const done = Bun.spawnSync(args, { cwd, stdout: "inherit", stderr: "inherit" });
  if (done.exitCode !== 0) throw new Error(`ui: ${args.slice(0, 3).join(" ")} failed`);
}

/** Cells of `count` squares of `cell` pixels from a strip, each scaled to `side` and `side * 2`. */
async function cut(image: Image, count: number, cell: number, name: (i: number) => string) {
  for (let i = 0; i < count; i++) {
    for (const [scale, suffix] of [[1, ""], [2, "@2x"]] as const) {
      const side = SIDE * scale;
      const canvas = createCanvas(side, side);
      const ctx = canvas.getContext("2d");
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, i * cell, 0, cell, cell, 0, 0, side, side);
      writeFileSync(join(generated, `${name(i)}${suffix}.png`), canvas.toBuffer("image/png"));
    }
  }
}

/**
 * Writes what the interface compiles from the reference (`ui/app/generated/`,
 * ignored): a picture of each tile of the diffuse atlas (a material `m` is
 * tile `m - 1`) and of each item icon, and `pictures.ts`, which lists their
 * names as literals (the compiler bakes the pictures whose names it finds)
 * with the version from `pocket.json`.
 */
export async function prepareInterface(): Promise<void> {
  const atlas = join(baked, "atlas_diff.png"), items = join(baked, "items.png");
  if (!existsSync(atlas)) throw new Error("ui: ref/ethertum is not checked out (git submodule update --init ref/ethertum)");
  mkdirSync(generated, { recursive: true });
  const stamp = join(generated, ".pictures");
  if (!existsSync(stamp) || statSync(stamp).mtimeMs < Math.max(statSync(atlas).mtimeMs, statSync(items).mtimeMs, statSync(import.meta.path).mtimeMs)) {
    await cut(await loadImage(atlas), TILES, 256, (i) => `tile-${i}`);
    await cut(await loadImage(items), ICONS, 64, (i) => `item-${i}`);
    writeFileSync(stamp, "");
  }
  const version = (await Bun.file(manifest).json()).version as string;
  const list = (prefix: string, count: number) => Array.from({ length: count }, (_, i) => `  "generated/${prefix}-${i}.png",`).join("\n");
  writeFileSync(join(generated, "pictures.ts"), `// Generated by tools/ui.ts from ref/ethertum/assets/baked and ui/pocket.json.

export const VERSION = ${JSON.stringify(version)};

/** A picture per tile of the diffuse atlas: material \`m\` is tile \`m - 1\`. */
export const TILES: string[] = [
${list("tile", TILES)}
];

/** A picture per icon of \`items.png\`, in the reference's registry order. */
export const ICONS: string[] = [
${list("item", ICONS)}
];
`);
}

export async function compileInterface(device: Device): Promise<Interface> {
  await prepareInterface();
  const directory = join(root, ".pocket-build/ui", device);
  mkdirSync(directory, { recursive: true });
  const planPath = join(directory, "plan.json");
  run(["bun", "tools/pocket.ts", "compile", "--target", device, "--manifest", manifest, "--project-root", project, "--outdir", directory]);
  await Bun.write(planPath, Bun.file(join(project, ".pocket", device, "plan.json")));
  const plan = await Bun.file(planPath).json();
  return { directory, plan, inputs: extractHostBuildInputs(plan) };
}

if (import.meta.main) {
  const [command, ...rest] = process.argv.slice(2);
  if (command === "prepare") await prepareInterface();
  else if (command === "preview" || command === "test") {
    // Both run the bundle on PocketJS's UI core built for wasm.
    if (!existsSync(join(pocket, "hosts/web/pocketjs.wasm"))) run(["bun", "tools/wasm.ts"]);
    // One process per device: a bundle owns `globalThis.frame`.
    for (const device of rest.length ? (rest as Device[]) : DEVICES) {
      await compileInterface(device);
      run(["bun", `ui/test/${command === "test" ? "flow" : "preview"}.ts`, device], root);
    }
  } else if (DEVICES.includes(command as Device)) {
    const built = await compileInterface(command as Device);
    console.log(`${command}: ${built.inputs.target}, ${built.inputs.viewport.logical.join("×")} @${built.inputs.viewport.rasterDensity}x → ${built.directory}`);
  } else throw new Error(`usage: bun tools/ui.ts <${DEVICES.join("|")}|prepare|preview [device…]|test>`);
}
